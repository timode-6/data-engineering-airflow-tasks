-- Checks used to verify the loads (README, "Results"). Run one query at a time

USE ROLE AIRLINE_ETL;
USE WAREHOUSE AIRLINE_WH;
USE DATABASE AIRLINE_DWH;

-- 1. Rows inserted / updated per table in the last four runs, oldest first
WITH runs AS (
  SELECT RUN_ID, MIN(LOG_ID) AS first_log_id
  FROM AIRLINE_DWH.AUDIT.LOAD_LOG
  GROUP BY RUN_ID
  ORDER BY first_log_id DESC
  LIMIT 4
),
numbered AS (
  SELECT RUN_ID, ROW_NUMBER() OVER (ORDER BY first_log_id) AS n FROM runs
)
SELECT l.TARGET_TABLE,
       MAX(IFF(r.n = 1, l.ROWS_INSERTED || ' / ' || l.ROWS_UPDATED, NULL)) AS initial_load,
       MAX(IFF(r.n = 2, l.ROWS_INSERTED || ' / ' || l.ROWS_UPDATED, NULL)) AS changes,
       MAX(IFF(r.n = 3, l.ROWS_INSERTED || ' / ' || l.ROWS_UPDATED, NULL)) AS changes_again,
       MAX(IFF(r.n = 4, l.ROWS_INSERTED || ' / ' || l.ROWS_UPDATED, NULL)) AS rebuild,
       LISTAGG(DISTINCT l.STATUS, ', ') AS status
FROM AIRLINE_DWH.AUDIT.LOAD_LOG l
JOIN numbered r ON r.RUN_ID = l.RUN_ID
GROUP BY l.TARGET_TABLE
ORDER BY MIN(l.LOG_ID);

-- 2. State check. The marts against a recomputation from scratch, the CDC test's
-- changes, and a fingerprint of all business data in CORE
WITH daily AS (
  SELECT DEPARTURE_DATE, CONTINENT_CODE, CONTINENT_NAME, COUNT(*) AS FLIGHTS,
         COUNT_IF(FLIGHT_STATUS = 'On Time') AS ON_TIME,
         COUNT_IF(FLIGHT_STATUS = 'Delayed') AS DELAYED,
         COUNT_IF(FLIGHT_STATUS = 'Cancelled') AS CANCELLED
  FROM AIRLINE_DWH.CORE.V_FLIGHT_DETAILS
  GROUP BY DEPARTURE_DATE, CONTINENT_CODE, CONTINENT_NAME
),
daily_mart AS (
  SELECT DEPARTURE_DATE, CONTINENT_CODE, CONTINENT_NAME, FLIGHTS, ON_TIME, DELAYED, CANCELLED
  FROM AIRLINE_DWH.MART.FLIGHTS_DAILY WHERE FLIGHTS > 0
),
airports AS (
  SELECT AIRPORT_ID, AIRPORT_NAME, IATA_CODE, COUNTRY_NAME, CONTINENT_NAME, COUNT(*) AS FLIGHTS,
         COUNT_IF(FLIGHT_STATUS = 'Delayed') AS DELAYED,
         COUNT_IF(FLIGHT_STATUS = 'Cancelled') AS CANCELLED
  FROM AIRLINE_DWH.CORE.V_FLIGHT_DETAILS
  GROUP BY AIRPORT_ID, AIRPORT_NAME, IATA_CODE, COUNTRY_NAME, CONTINENT_NAME
),
airports_mart AS (
  SELECT AIRPORT_ID, AIRPORT_NAME, IATA_CODE, COUNTRY_NAME, CONTINENT_NAME, FLIGHTS, DELAYED, CANCELLED
  FROM AIRLINE_DWH.MART.AIRPORT_PERFORMANCE WHERE FLIGHTS > 0
),
profiles AS (
  SELECT NATIONALITY, GENDER, AGE_GROUP, COUNT(*) AS PASSENGERS,
         COUNT_IF(FLIGHT_STATUS = 'On Time') AS ON_TIME,
         COUNT_IF(FLIGHT_STATUS = 'Delayed') AS DELAYED,
         COUNT_IF(FLIGHT_STATUS = 'Cancelled') AS CANCELLED
  FROM AIRLINE_DWH.CORE.V_FLIGHT_DETAILS
  GROUP BY NATIONALITY, GENDER, AGE_GROUP
),
profiles_mart AS (
  SELECT NATIONALITY, GENDER, AGE_GROUP, PASSENGERS, ON_TIME, DELAYED, CANCELLED
  FROM AIRLINE_DWH.MART.PASSENGER_PROFILE WHERE PASSENGERS > 0
),
changed_twice AS (
  SELECT PASSENGER_ID
  FROM AIRLINE_DWH.RAW.AIRLINE_BOOKINGS
  WHERE SOURCE_FILE LIKE '%changes%'
  GROUP BY PASSENGER_ID
  HAVING COUNT(*) = 2
)
SELECT
  -- mart rows that differ from a recomputation from scratch, both directions
  -- (a group that empties out keeps a row of zeros, so those are left out)
  (SELECT COUNT(*) FROM (SELECT * FROM daily_mart MINUS SELECT * FROM daily))
  + (SELECT COUNT(*) FROM (SELECT * FROM daily MINUS SELECT * FROM daily_mart))
  + (SELECT COUNT(*) FROM (SELECT * FROM airports_mart MINUS SELECT * FROM airports))
  + (SELECT COUNT(*) FROM (SELECT * FROM airports MINUS SELECT * FROM airports_mart))
  + (SELECT COUNT(*) FROM (SELECT * FROM profiles_mart MINUS SELECT * FROM profiles))
  + (SELECT COUNT(*) FROM (SELECT * FROM profiles MINUS SELECT * FROM profiles_mart)) AS mart_rows_off,
  (SELECT COUNT(*) FROM AIRLINE_DWH.CORE.FACT_FLIGHT) AS flights,
  (SELECT COUNT(*) FROM changed_twice) AS changed_twice,
  (SELECT COUNT(*) FROM AIRLINE_DWH.CORE.FACT_FLIGHT f JOIN changed_twice c ON c.PASSENGER_ID = f.PASSENGER_ID
   WHERE f.FLIGHT_STATUS = 'Cancelled') AS now_cancelled,
  (SELECT COUNTRY_NAME FROM AIRLINE_DWH.CORE.DIM_COUNTRY WHERE COUNTRY_CODE = 'TR') AS tr_name,
  (SELECT COUNT_IF(COUNTRY_NAME = 'Türkiye') FROM AIRLINE_DWH.MART.AIRPORT_PERFORMANCE) AS airports_tuerkiye,
  (SELECT COUNT_IF(COUNTRY_NAME = 'Turkey') FROM AIRLINE_DWH.MART.AIRPORT_PERFORMANCE) AS airports_turkey,
  (SELECT HASH_AGG(f.PASSENGER_ID, f.DEPARTURE_DATE_KEY, a.AIRPORT_NAME, a.COUNTRY_CODE,
                   a.AIRPORT_CODE, a.IATA_CODE, a.CONTINENT_CODE, c.COUNTRY_NAME,
                   k.CONTINENT_NAME, p.FIRST_NAME, p.LAST_NAME, p.GENDER, p.AGE,
                   p.NATIONALITY, f.PILOT_NAME, f.FLIGHT_STATUS, f.TICKET_TYPE,
                   f.PASSENGER_STATUS)
   FROM AIRLINE_DWH.CORE.FACT_FLIGHT f
   JOIN AIRLINE_DWH.CORE.DIM_AIRPORT a   ON a.AIRPORT_ID = f.AIRPORT_ID
   JOIN AIRLINE_DWH.CORE.DIM_COUNTRY c   ON c.COUNTRY_CODE = a.COUNTRY_CODE
   JOIN AIRLINE_DWH.CORE.DIM_CONTINENT k ON k.CONTINENT_CODE = a.CONTINENT_CODE
   JOIN AIRLINE_DWH.CORE.DIM_PASSENGER p ON p.PASSENGER_ID = f.PASSENGER_ID) AS core_fingerprint;

-- 3. The same fingerprint at the end of the CDC path, read through time travel,
-- next to the fingerprint now
SET after_changes = (SELECT MIN(STARTED_AT) FROM AIRLINE_DWH.AUDIT.LOAD_LOG
                     WHERE RUN_ID = 'manual__2026-10-26T08:21:25.259899+00:00');
SELECT
  (SELECT HASH_AGG(f.PASSENGER_ID, f.DEPARTURE_DATE_KEY, a.AIRPORT_NAME, a.COUNTRY_CODE,
                   a.AIRPORT_CODE, a.IATA_CODE, a.CONTINENT_CODE, c.COUNTRY_NAME,
                   k.CONTINENT_NAME, p.FIRST_NAME, p.LAST_NAME, p.GENDER, p.AGE,
                   p.NATIONALITY, f.PILOT_NAME, f.FLIGHT_STATUS, f.TICKET_TYPE,
                   f.PASSENGER_STATUS)
   FROM AIRLINE_DWH.CORE.FACT_FLIGHT   AT(TIMESTAMP => $after_changes::TIMESTAMP_LTZ) f
   JOIN AIRLINE_DWH.CORE.DIM_AIRPORT   AT(TIMESTAMP => $after_changes::TIMESTAMP_LTZ) a ON a.AIRPORT_ID = f.AIRPORT_ID
   JOIN AIRLINE_DWH.CORE.DIM_COUNTRY   AT(TIMESTAMP => $after_changes::TIMESTAMP_LTZ) c ON c.COUNTRY_CODE = a.COUNTRY_CODE
   JOIN AIRLINE_DWH.CORE.DIM_CONTINENT AT(TIMESTAMP => $after_changes::TIMESTAMP_LTZ) k ON k.CONTINENT_CODE = a.CONTINENT_CODE
   JOIN AIRLINE_DWH.CORE.DIM_PASSENGER AT(TIMESTAMP => $after_changes::TIMESTAMP_LTZ) p ON p.PASSENGER_ID = f.PASSENGER_ID
  ) AS after_cdc_path,
  (SELECT HASH_AGG(f.PASSENGER_ID, f.DEPARTURE_DATE_KEY, a.AIRPORT_NAME, a.COUNTRY_CODE,
                   a.AIRPORT_CODE, a.IATA_CODE, a.CONTINENT_CODE, c.COUNTRY_NAME,
                   k.CONTINENT_NAME, p.FIRST_NAME, p.LAST_NAME, p.GENDER, p.AGE,
                   p.NATIONALITY, f.PILOT_NAME, f.FLIGHT_STATUS, f.TICKET_TYPE,
                   f.PASSENGER_STATUS)
   FROM AIRLINE_DWH.CORE.FACT_FLIGHT f
   JOIN AIRLINE_DWH.CORE.DIM_AIRPORT a   ON a.AIRPORT_ID = f.AIRPORT_ID
   JOIN AIRLINE_DWH.CORE.DIM_COUNTRY c   ON c.COUNTRY_CODE = a.COUNTRY_CODE
   JOIN AIRLINE_DWH.CORE.DIM_CONTINENT k ON k.CONTINENT_CODE = a.CONTINENT_CODE
   JOIN AIRLINE_DWH.CORE.DIM_PASSENGER p ON p.PASSENGER_ID = f.PASSENGER_ID
  ) AS after_rebuild,
  after_cdc_path = after_rebuild AS same_data;
