-- Stage 3, MART: three aggregates for dashboards, kept up to date incrementally

USE ROLE AIRLINE_ETL;
USE WAREHOUSE AIRLINE_WH;
USE DATABASE AIRLINE_DWH;

-- Everything a mart needs about a flight, in one row. Every column a mart
-- groups by or shows is here, so a change to any of them reaches the stream
-- below, with the old and the new values: a new or updated flight, and also a
-- renamed country, which puts all of that country's flights into the stream
CREATE OR REPLACE VIEW CORE.V_FLIGHT_DETAILS AS
SELECT
  f.PASSENGER_ID,
  d.FULL_DATE AS DEPARTURE_DATE,
  f.AIRPORT_ID,
  a.AIRPORT_NAME,
  a.IATA_CODE,
  c.COUNTRY_NAME,
  a.CONTINENT_CODE,
  k.CONTINENT_NAME,
  p.NATIONALITY,
  p.GENDER,
  CASE WHEN p.AGE < 18 THEN '0-17'
       WHEN p.AGE < 35 THEN '18-34'
       WHEN p.AGE < 55 THEN '35-54'
       WHEN p.AGE < 75 THEN '55-74'
       WHEN p.AGE >= 75 THEN '75+'
       ELSE 'Unknown' END AS AGE_GROUP,
  f.FLIGHT_STATUS
FROM AIRLINE_DWH.CORE.FACT_FLIGHT f
JOIN AIRLINE_DWH.CORE.DIM_DATE d      ON d.DATE_KEY = f.DEPARTURE_DATE_KEY
JOIN AIRLINE_DWH.CORE.DIM_AIRPORT a   ON a.AIRPORT_ID = f.AIRPORT_ID
JOIN AIRLINE_DWH.CORE.DIM_COUNTRY c   ON c.COUNTRY_CODE = a.COUNTRY_CODE
JOIN AIRLINE_DWH.CORE.DIM_CONTINENT k ON k.CONTINENT_CODE = a.CONTINENT_CODE
JOIN AIRLINE_DWH.CORE.DIM_PASSENGER p ON p.PASSENGER_ID = f.PASSENGER_ID;

-- Replacing the view needs a new stream on it. Run this file between loads:
-- the new stream starts empty
CREATE OR REPLACE STREAM CORE.FLIGHT_DETAILS_STREAM ON VIEW CORE.V_FLIGHT_DETAILS;

CREATE TABLE IF NOT EXISTS MART.FLIGHTS_DAILY (
  DEPARTURE_DATE  DATE NOT NULL,
  CONTINENT_CODE  VARCHAR(3) NOT NULL,
  CONTINENT_NAME  VARCHAR NOT NULL,
  FLIGHTS         NUMBER NOT NULL,
  ON_TIME         NUMBER NOT NULL,
  DELAYED         NUMBER NOT NULL,
  CANCELLED       NUMBER NOT NULL,
  ON_TIME_PCT     NUMBER(5,2),
  UPDATED_AT      TIMESTAMP_LTZ NOT NULL,
  CONSTRAINT PK_FLIGHTS_DAILY PRIMARY KEY (DEPARTURE_DATE, CONTINENT_CODE)
);

CREATE TABLE IF NOT EXISTS MART.AIRPORT_PERFORMANCE (
  AIRPORT_ID      NUMBER NOT NULL,
  AIRPORT_NAME    VARCHAR NOT NULL,
  IATA_CODE       VARCHAR(3),
  COUNTRY_NAME    VARCHAR NOT NULL,
  CONTINENT_NAME  VARCHAR NOT NULL,
  FLIGHTS         NUMBER NOT NULL,
  DELAYED         NUMBER NOT NULL,
  CANCELLED       NUMBER NOT NULL,
  DELAYED_PCT     NUMBER(5,2),
  CANCELLED_PCT   NUMBER(5,2),
  UPDATED_AT      TIMESTAMP_LTZ NOT NULL,
  CONSTRAINT PK_AIRPORT_PERFORMANCE PRIMARY KEY (AIRPORT_ID)
);

CREATE TABLE IF NOT EXISTS MART.PASSENGER_PROFILE (
  NATIONALITY    VARCHAR NOT NULL,
  GENDER         VARCHAR NOT NULL,
  AGE_GROUP      VARCHAR NOT NULL,
  PASSENGERS     NUMBER NOT NULL,
  ON_TIME        NUMBER NOT NULL,
  DELAYED        NUMBER NOT NULL,
  CANCELLED      NUMBER NOT NULL,
  CANCELLED_PCT  NUMBER(5,2),
  UPDATED_AT     TIMESTAMP_LTZ NOT NULL,
  CONSTRAINT PK_PASSENGER_PROFILE PRIMARY KEY (NATIONALITY, GENDER, AGE_GROUP)
);

CREATE OR REPLACE PROCEDURE MART.LOAD_MARTS(RUN_ID VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
DECLARE
  started_at   TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP();
  rows_before  NUMBER;
  affected     NUMBER;
  summary      VARCHAR;
  err          VARCHAR;
BEGIN
  BEGIN TRANSACTION;

  SELECT COUNT(*) INTO :rows_before FROM AIRLINE_DWH.MART.FLIGHTS_DAILY;
  MERGE INTO AIRLINE_DWH.MART.FLIGHTS_DAILY t
  USING (
    SELECT ch.DEPARTURE_DATE, ch.CONTINENT_CODE, k.CONTINENT_NAME,
           COUNT(v.PASSENGER_ID)                   AS FLIGHTS,
           COUNT_IF(v.FLIGHT_STATUS = 'On Time')   AS ON_TIME,
           COUNT_IF(v.FLIGHT_STATUS = 'Delayed')   AS DELAYED,
           COUNT_IF(v.FLIGHT_STATUS = 'Cancelled') AS CANCELLED
    FROM (SELECT DISTINCT DEPARTURE_DATE, CONTINENT_CODE
          FROM AIRLINE_DWH.CORE.FLIGHT_DETAILS_STREAM) ch
    JOIN AIRLINE_DWH.CORE.DIM_CONTINENT k ON k.CONTINENT_CODE = ch.CONTINENT_CODE
    LEFT JOIN AIRLINE_DWH.CORE.V_FLIGHT_DETAILS v
      ON v.DEPARTURE_DATE = ch.DEPARTURE_DATE AND v.CONTINENT_CODE = ch.CONTINENT_CODE
    GROUP BY ch.DEPARTURE_DATE, ch.CONTINENT_CODE, k.CONTINENT_NAME
  ) s
  ON t.DEPARTURE_DATE = s.DEPARTURE_DATE AND t.CONTINENT_CODE = s.CONTINENT_CODE
  WHEN MATCHED AND (t.FLIGHTS <> s.FLIGHTS OR t.ON_TIME <> s.ON_TIME
                 OR t.DELAYED <> s.DELAYED OR t.CANCELLED <> s.CANCELLED
                 OR t.CONTINENT_NAME IS DISTINCT FROM s.CONTINENT_NAME) THEN
    UPDATE SET CONTINENT_NAME = s.CONTINENT_NAME, FLIGHTS = s.FLIGHTS, ON_TIME = s.ON_TIME,
               DELAYED = s.DELAYED, CANCELLED = s.CANCELLED,
               ON_TIME_PCT = ROUND(100 * s.ON_TIME / NULLIF(s.FLIGHTS, 0), 2),
               UPDATED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED AND s.FLIGHTS > 0 THEN
    INSERT (DEPARTURE_DATE, CONTINENT_CODE, CONTINENT_NAME, FLIGHTS, ON_TIME,
            DELAYED, CANCELLED, ON_TIME_PCT, UPDATED_AT)
    VALUES (s.DEPARTURE_DATE, s.CONTINENT_CODE, s.CONTINENT_NAME, s.FLIGHTS, s.ON_TIME,
            s.DELAYED, s.CANCELLED, ROUND(100 * s.ON_TIME / NULLIF(s.FLIGHTS, 0), 2),
            CURRENT_TIMESTAMP());
  affected := SQLROWCOUNT;
  CALL AIRLINE_DWH.AUDIT.LOG_MERGE(:RUN_ID, 'MART.LOAD_MARTS', 'MART.FLIGHTS_DAILY', :rows_before, :affected, :started_at);

  SELECT COUNT(*) INTO :rows_before FROM AIRLINE_DWH.MART.AIRPORT_PERFORMANCE;
  MERGE INTO AIRLINE_DWH.MART.AIRPORT_PERFORMANCE t
  USING (
    SELECT a.AIRPORT_ID, a.AIRPORT_NAME, a.IATA_CODE, c.COUNTRY_NAME, k.CONTINENT_NAME,
           COUNT(v.PASSENGER_ID)                   AS FLIGHTS,
           COUNT_IF(v.FLIGHT_STATUS = 'Delayed')   AS DELAYED,
           COUNT_IF(v.FLIGHT_STATUS = 'Cancelled') AS CANCELLED
    FROM (SELECT DISTINCT AIRPORT_ID FROM AIRLINE_DWH.CORE.FLIGHT_DETAILS_STREAM) ch
    JOIN AIRLINE_DWH.CORE.DIM_AIRPORT a   ON a.AIRPORT_ID = ch.AIRPORT_ID
    JOIN AIRLINE_DWH.CORE.DIM_COUNTRY c   ON c.COUNTRY_CODE = a.COUNTRY_CODE
    JOIN AIRLINE_DWH.CORE.DIM_CONTINENT k ON k.CONTINENT_CODE = a.CONTINENT_CODE
    LEFT JOIN AIRLINE_DWH.CORE.V_FLIGHT_DETAILS v ON v.AIRPORT_ID = ch.AIRPORT_ID
    GROUP BY a.AIRPORT_ID, a.AIRPORT_NAME, a.IATA_CODE, c.COUNTRY_NAME, k.CONTINENT_NAME
  ) s
  ON t.AIRPORT_ID = s.AIRPORT_ID
  WHEN MATCHED AND (t.FLIGHTS <> s.FLIGHTS OR t.DELAYED <> s.DELAYED
                 OR t.CANCELLED <> s.CANCELLED
                 OR t.AIRPORT_NAME IS DISTINCT FROM s.AIRPORT_NAME
                 OR t.IATA_CODE IS DISTINCT FROM s.IATA_CODE
                 OR t.COUNTRY_NAME IS DISTINCT FROM s.COUNTRY_NAME
                 OR t.CONTINENT_NAME IS DISTINCT FROM s.CONTINENT_NAME) THEN
    UPDATE SET AIRPORT_NAME = s.AIRPORT_NAME, IATA_CODE = s.IATA_CODE,
               COUNTRY_NAME = s.COUNTRY_NAME, CONTINENT_NAME = s.CONTINENT_NAME,
               FLIGHTS = s.FLIGHTS, DELAYED = s.DELAYED, CANCELLED = s.CANCELLED,
               DELAYED_PCT = ROUND(100 * s.DELAYED / NULLIF(s.FLIGHTS, 0), 2),
               CANCELLED_PCT = ROUND(100 * s.CANCELLED / NULLIF(s.FLIGHTS, 0), 2),
               UPDATED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED AND s.FLIGHTS > 0 THEN
    INSERT (AIRPORT_ID, AIRPORT_NAME, IATA_CODE, COUNTRY_NAME, CONTINENT_NAME, FLIGHTS,
            DELAYED, CANCELLED, DELAYED_PCT, CANCELLED_PCT, UPDATED_AT)
    VALUES (s.AIRPORT_ID, s.AIRPORT_NAME, s.IATA_CODE, s.COUNTRY_NAME, s.CONTINENT_NAME,
            s.FLIGHTS, s.DELAYED, s.CANCELLED,
            ROUND(100 * s.DELAYED / NULLIF(s.FLIGHTS, 0), 2),
            ROUND(100 * s.CANCELLED / NULLIF(s.FLIGHTS, 0), 2),
            CURRENT_TIMESTAMP());
  affected := SQLROWCOUNT;
  CALL AIRLINE_DWH.AUDIT.LOG_MERGE(:RUN_ID, 'MART.LOAD_MARTS', 'MART.AIRPORT_PERFORMANCE', :rows_before, :affected, :started_at);

  SELECT COUNT(*) INTO :rows_before FROM AIRLINE_DWH.MART.PASSENGER_PROFILE;
  MERGE INTO AIRLINE_DWH.MART.PASSENGER_PROFILE t
  USING (
    SELECT ch.NATIONALITY, ch.GENDER, ch.AGE_GROUP,
           COUNT(v.PASSENGER_ID)                   AS PASSENGERS,
           COUNT_IF(v.FLIGHT_STATUS = 'On Time')   AS ON_TIME,
           COUNT_IF(v.FLIGHT_STATUS = 'Delayed')   AS DELAYED,
           COUNT_IF(v.FLIGHT_STATUS = 'Cancelled') AS CANCELLED
    FROM (SELECT DISTINCT NATIONALITY, GENDER, AGE_GROUP
          FROM AIRLINE_DWH.CORE.FLIGHT_DETAILS_STREAM) ch
    LEFT JOIN AIRLINE_DWH.CORE.V_FLIGHT_DETAILS v
      ON v.NATIONALITY = ch.NATIONALITY AND v.GENDER = ch.GENDER
     AND v.AGE_GROUP = ch.AGE_GROUP
    GROUP BY ch.NATIONALITY, ch.GENDER, ch.AGE_GROUP
  ) s
  ON t.NATIONALITY = s.NATIONALITY AND t.GENDER = s.GENDER AND t.AGE_GROUP = s.AGE_GROUP
  WHEN MATCHED AND (t.PASSENGERS <> s.PASSENGERS OR t.ON_TIME <> s.ON_TIME
                 OR t.DELAYED <> s.DELAYED OR t.CANCELLED <> s.CANCELLED) THEN
    UPDATE SET PASSENGERS = s.PASSENGERS, ON_TIME = s.ON_TIME, DELAYED = s.DELAYED,
               CANCELLED = s.CANCELLED,
               CANCELLED_PCT = ROUND(100 * s.CANCELLED / NULLIF(s.PASSENGERS, 0), 2),
               UPDATED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED AND s.PASSENGERS > 0 THEN
    INSERT (NATIONALITY, GENDER, AGE_GROUP, PASSENGERS, ON_TIME, DELAYED, CANCELLED,
            CANCELLED_PCT, UPDATED_AT)
    VALUES (s.NATIONALITY, s.GENDER, s.AGE_GROUP, s.PASSENGERS, s.ON_TIME, s.DELAYED,
            s.CANCELLED, ROUND(100 * s.CANCELLED / NULLIF(s.PASSENGERS, 0), 2),
            CURRENT_TIMESTAMP());
  affected := SQLROWCOUNT;
  CALL AIRLINE_DWH.AUDIT.LOG_MERGE(:RUN_ID, 'MART.LOAD_MARTS', 'MART.PASSENGER_PROFILE', :rows_before, :affected, :started_at);

  COMMIT;

  SELECT LISTAGG(TARGET_TABLE || ' +' || ROWS_INSERTED || ' ~' || ROWS_UPDATED, ', ')
           WITHIN GROUP (ORDER BY LOG_ID)
    INTO :summary
  FROM AIRLINE_DWH.AUDIT.LOAD_LOG
  WHERE RUN_ID = :RUN_ID AND PROCEDURE_NAME = 'MART.LOAD_MARTS' AND STARTED_AT = :started_at;
  RETURN summary;
EXCEPTION
  WHEN OTHER THEN
    err := SQLERRM;
    ROLLBACK;
    INSERT INTO AIRLINE_DWH.AUDIT.LOAD_LOG
      (RUN_ID, PROCEDURE_NAME, TARGET_TABLE, STATUS, ERROR_MESSAGE, STARTED_AT, FINISHED_AT)
    VALUES (:RUN_ID, 'MART.LOAD_MARTS', 'MART.*', 'FAILED', :err, :started_at, CURRENT_TIMESTAMP());
    RAISE;
END;
$$;
