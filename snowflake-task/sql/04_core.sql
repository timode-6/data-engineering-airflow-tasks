-- Stage 2, CORE: cleaned, typed data in a star schema, with constraints
-- Grain of the fact: one flight per passenger (every passenger books once)
--
-- Snowflake enforces only NOT NULL. Primary, unique and foreign keys are
-- recorded for tools and readers, and LOAD_CORE's MERGEs keep them true

USE ROLE AIRLINE_ETL;
USE WAREHOUSE AIRLINE_WH;
USE DATABASE AIRLINE_DWH;

CREATE TABLE IF NOT EXISTS CORE.DIM_CONTINENT (
  CONTINENT_CODE  VARCHAR(3) NOT NULL,
  CONTINENT_NAME  VARCHAR NOT NULL,
  UPDATED_AT      TIMESTAMP_LTZ NOT NULL,
  CONSTRAINT PK_DIM_CONTINENT PRIMARY KEY (CONTINENT_CODE),
  CONSTRAINT UQ_DIM_CONTINENT_NAME UNIQUE (CONTINENT_NAME)
);

CREATE TABLE IF NOT EXISTS CORE.DIM_COUNTRY (
  COUNTRY_CODE  VARCHAR(2) NOT NULL,
  COUNTRY_NAME  VARCHAR NOT NULL,
  UPDATED_AT    TIMESTAMP_LTZ NOT NULL,
  CONSTRAINT PK_DIM_COUNTRY PRIMARY KEY (COUNTRY_CODE),
  CONSTRAINT UQ_DIM_COUNTRY_NAME UNIQUE (COUNTRY_NAME)
);

-- DATE_KEY is the date as YYYYMMDD; DAY_OF_WEEK is ISO (Monday = 1)
CREATE TABLE IF NOT EXISTS CORE.DIM_DATE (
  DATE_KEY      NUMBER(8) NOT NULL,
  FULL_DATE     DATE NOT NULL,
  YEAR          NUMBER(4) NOT NULL,
  QUARTER       NUMBER(1) NOT NULL,
  MONTH         NUMBER(2) NOT NULL,
  MONTH_NAME    VARCHAR(3) NOT NULL,
  DAY_OF_MONTH  NUMBER(2) NOT NULL,
  DAY_OF_WEEK   NUMBER(1) NOT NULL,
  DAY_NAME      VARCHAR(3) NOT NULL,
  IS_WEEKEND    BOOLEAN NOT NULL,
  CONSTRAINT PK_DIM_DATE PRIMARY KEY (DATE_KEY),
  CONSTRAINT UQ_DIM_DATE_FULL_DATE UNIQUE (FULL_DATE)
);

CREATE TABLE IF NOT EXISTS CORE.DIM_PASSENGER (
  PASSENGER_ID  VARCHAR NOT NULL,
  FIRST_NAME    VARCHAR NOT NULL,
  LAST_NAME     VARCHAR NOT NULL,
  GENDER        VARCHAR NOT NULL,
  AGE           NUMBER(3) NOT NULL,
  NATIONALITY   VARCHAR NOT NULL,
  CREATED_AT    TIMESTAMP_LTZ NOT NULL,
  UPDATED_AT    TIMESTAMP_LTZ NOT NULL,
  CONSTRAINT PK_DIM_PASSENGER PRIMARY KEY (PASSENGER_ID)
);

-- An airport is its name, country and code together: the source has no
-- airport id, and some codes are not IATA codes ('0', '-', 'SB2', ...)
-- IATA_CODE keeps only the real ones; AIRPORT_ID is a surrogate key
CREATE TABLE IF NOT EXISTS CORE.DIM_AIRPORT (
  AIRPORT_ID      NUMBER AUTOINCREMENT START 1 INCREMENT 1 NOORDER NOT NULL,
  AIRPORT_NAME    VARCHAR NOT NULL,
  COUNTRY_CODE    VARCHAR(2) NOT NULL,
  AIRPORT_CODE    VARCHAR NOT NULL,
  IATA_CODE       VARCHAR(3),
  CONTINENT_CODE  VARCHAR(3) NOT NULL,
  UPDATED_AT      TIMESTAMP_LTZ NOT NULL,
  CONSTRAINT PK_DIM_AIRPORT PRIMARY KEY (AIRPORT_ID),
  CONSTRAINT UQ_DIM_AIRPORT UNIQUE (AIRPORT_NAME, COUNTRY_CODE, AIRPORT_CODE),
  CONSTRAINT FK_AIRPORT_COUNTRY FOREIGN KEY (COUNTRY_CODE)
    REFERENCES CORE.DIM_COUNTRY (COUNTRY_CODE),
  CONSTRAINT FK_AIRPORT_CONTINENT FOREIGN KEY (CONTINENT_CODE)
    REFERENCES CORE.DIM_CONTINENT (CONTINENT_CODE)
);

-- SOURCE_FILE and SOURCE_ROW say which line the current version came from
CREATE TABLE IF NOT EXISTS CORE.FACT_FLIGHT (
  PASSENGER_ID        VARCHAR NOT NULL,
  DEPARTURE_DATE_KEY  NUMBER(8) NOT NULL,
  AIRPORT_ID          NUMBER NOT NULL,
  PILOT_NAME          VARCHAR NOT NULL,
  FLIGHT_STATUS       VARCHAR NOT NULL,
  TICKET_TYPE         VARCHAR NOT NULL,
  PASSENGER_STATUS    VARCHAR NOT NULL,
  SOURCE_FILE         VARCHAR NOT NULL,
  SOURCE_ROW          NUMBER NOT NULL,
  CREATED_AT          TIMESTAMP_LTZ NOT NULL,
  UPDATED_AT          TIMESTAMP_LTZ NOT NULL,
  CONSTRAINT PK_FACT_FLIGHT PRIMARY KEY (PASSENGER_ID),
  CONSTRAINT FK_FLIGHT_PASSENGER FOREIGN KEY (PASSENGER_ID)
    REFERENCES CORE.DIM_PASSENGER (PASSENGER_ID),
  CONSTRAINT FK_FLIGHT_DATE FOREIGN KEY (DEPARTURE_DATE_KEY)
    REFERENCES CORE.DIM_DATE (DATE_KEY),
  CONSTRAINT FK_FLIGHT_AIRPORT FOREIGN KEY (AIRPORT_ID)
    REFERENCES CORE.DIM_AIRPORT (AIRPORT_ID)
);

-- What LOAD_CORE reads: the raw rows the stream has not delivered yet, trimmed
-- and typed. One batch can hold several files, so the same passenger can
-- appear more than once; the newest row wins
CREATE OR REPLACE VIEW CORE.V_BOOKINGS_CHANGES AS
SELECT
  TRIM(PASSENGER_ID)                              AS PASSENGER_ID,
  TRIM(FIRST_NAME)                                AS FIRST_NAME,
  TRIM(LAST_NAME)                                 AS LAST_NAME,
  TRIM(GENDER)                                    AS GENDER,
  TRY_TO_NUMBER(TRIM(AGE))                        AS AGE,
  TRIM(NATIONALITY)                               AS NATIONALITY,
  TRIM(AIRPORT_NAME)                              AS AIRPORT_NAME,
  UPPER(TRIM(AIRPORT_COUNTRY_CODE))               AS COUNTRY_CODE,
  TRIM(COUNTRY_NAME)                              AS COUNTRY_NAME,
  UPPER(TRIM(AIRPORT_CONTINENT))                  AS CONTINENT_CODE,
  TRIM(CONTINENTS)                                AS CONTINENT_NAME,
  TRIM(ARRIVAL_AIRPORT)                           AS AIRPORT_CODE,
  TRY_TO_DATE(TRIM(DEPARTURE_DATE), 'MM/DD/YYYY') AS DEPARTURE_DATE,
  TRIM(PILOT_NAME)                                AS PILOT_NAME,
  TRIM(FLIGHT_STATUS)                             AS FLIGHT_STATUS,
  TRIM(TICKET_TYPE)                               AS TICKET_TYPE,
  TRIM(PASSENGER_STATUS)                          AS PASSENGER_STATUS,
  SOURCE_FILE,
  SOURCE_ROW,
  LOADED_AT
FROM AIRLINE_DWH.RAW.AIRLINE_BOOKINGS_STREAM
-- The same passenger can arrive more than once; the latest row wins
QUALIFY ROW_NUMBER() OVER (
  PARTITION BY TRIM(PASSENGER_ID)
  ORDER BY LOADED_AT DESC, SOURCE_FILE DESC, SOURCE_ROW DESC) = 1;

CREATE OR REPLACE PROCEDURE CORE.LOAD_CORE(RUN_ID VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
DECLARE
  started_at   TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP();
  rows_before  NUMBER;
  affected     NUMBER;
  summary      VARCHAR;
  err          VARCHAR;
BEGIN
  -- One transaction: the stream moves on only if every MERGE succeeds,
  -- so a failed run leaves the same rows waiting for the next one
  BEGIN TRANSACTION;

  -- Dimensions take the latest row per key, in the order V_BOOKINGS_CHANGES
  -- uses for passengers. One batch can hold several files, so a code can
  -- arrive with an old and a new name; the newest one must win
  SELECT COUNT(*) INTO :rows_before FROM AIRLINE_DWH.CORE.DIM_CONTINENT;
  MERGE INTO AIRLINE_DWH.CORE.DIM_CONTINENT t
  USING (SELECT CONTINENT_CODE, CONTINENT_NAME
         FROM AIRLINE_DWH.CORE.V_BOOKINGS_CHANGES
         QUALIFY ROW_NUMBER() OVER (PARTITION BY CONTINENT_CODE
                   ORDER BY LOADED_AT DESC, SOURCE_FILE DESC, SOURCE_ROW DESC) = 1) s
  ON t.CONTINENT_CODE = s.CONTINENT_CODE
  WHEN MATCHED AND t.CONTINENT_NAME IS DISTINCT FROM s.CONTINENT_NAME THEN
    UPDATE SET CONTINENT_NAME = s.CONTINENT_NAME, UPDATED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN
    INSERT (CONTINENT_CODE, CONTINENT_NAME, UPDATED_AT)
    VALUES (s.CONTINENT_CODE, s.CONTINENT_NAME, CURRENT_TIMESTAMP());
  affected := SQLROWCOUNT;
  CALL AIRLINE_DWH.AUDIT.LOG_MERGE(:RUN_ID, 'CORE.LOAD_CORE', 'CORE.DIM_CONTINENT', :rows_before, :affected, :started_at);

  SELECT COUNT(*) INTO :rows_before FROM AIRLINE_DWH.CORE.DIM_COUNTRY;
  MERGE INTO AIRLINE_DWH.CORE.DIM_COUNTRY t
  USING (SELECT COUNTRY_CODE, COUNTRY_NAME
         FROM AIRLINE_DWH.CORE.V_BOOKINGS_CHANGES
         QUALIFY ROW_NUMBER() OVER (PARTITION BY COUNTRY_CODE
                   ORDER BY LOADED_AT DESC, SOURCE_FILE DESC, SOURCE_ROW DESC) = 1) s
  ON t.COUNTRY_CODE = s.COUNTRY_CODE
  WHEN MATCHED AND t.COUNTRY_NAME IS DISTINCT FROM s.COUNTRY_NAME THEN
    UPDATE SET COUNTRY_NAME = s.COUNTRY_NAME, UPDATED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN
    INSERT (COUNTRY_CODE, COUNTRY_NAME, UPDATED_AT)
    VALUES (s.COUNTRY_CODE, s.COUNTRY_NAME, CURRENT_TIMESTAMP());
  affected := SQLROWCOUNT;
  CALL AIRLINE_DWH.AUDIT.LOG_MERGE(:RUN_ID, 'CORE.LOAD_CORE', 'CORE.DIM_COUNTRY', :rows_before, :affected, :started_at);

  SELECT COUNT(*) INTO :rows_before FROM AIRLINE_DWH.CORE.DIM_DATE;
  MERGE INTO AIRLINE_DWH.CORE.DIM_DATE t
  USING (SELECT DISTINCT DEPARTURE_DATE AS D FROM AIRLINE_DWH.CORE.V_BOOKINGS_CHANGES) s
  ON t.FULL_DATE = s.D
  WHEN NOT MATCHED THEN
    INSERT (DATE_KEY, FULL_DATE, YEAR, QUARTER, MONTH, MONTH_NAME,
            DAY_OF_MONTH, DAY_OF_WEEK, DAY_NAME, IS_WEEKEND)
    VALUES (YEAR(s.D) * 10000 + MONTH(s.D) * 100 + DAY(s.D), s.D, YEAR(s.D),
            QUARTER(s.D), MONTH(s.D), MONTHNAME(s.D), DAY(s.D),
            DAYOFWEEKISO(s.D), DAYNAME(s.D), DAYOFWEEKISO(s.D) IN (6, 7));
  affected := SQLROWCOUNT;
  CALL AIRLINE_DWH.AUDIT.LOG_MERGE(:RUN_ID, 'CORE.LOAD_CORE', 'CORE.DIM_DATE', :rows_before, :affected, :started_at);

  SELECT COUNT(*) INTO :rows_before FROM AIRLINE_DWH.CORE.DIM_PASSENGER;
  MERGE INTO AIRLINE_DWH.CORE.DIM_PASSENGER t
  USING AIRLINE_DWH.CORE.V_BOOKINGS_CHANGES s
  ON t.PASSENGER_ID = s.PASSENGER_ID
  WHEN MATCHED AND (t.FIRST_NAME IS DISTINCT FROM s.FIRST_NAME
                 OR t.LAST_NAME IS DISTINCT FROM s.LAST_NAME
                 OR t.GENDER IS DISTINCT FROM s.GENDER
                 OR t.AGE IS DISTINCT FROM s.AGE
                 OR t.NATIONALITY IS DISTINCT FROM s.NATIONALITY) THEN
    UPDATE SET FIRST_NAME = s.FIRST_NAME, LAST_NAME = s.LAST_NAME, GENDER = s.GENDER,
               AGE = s.AGE, NATIONALITY = s.NATIONALITY, UPDATED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN
    INSERT (PASSENGER_ID, FIRST_NAME, LAST_NAME, GENDER, AGE, NATIONALITY, CREATED_AT, UPDATED_AT)
    VALUES (s.PASSENGER_ID, s.FIRST_NAME, s.LAST_NAME, s.GENDER, s.AGE, s.NATIONALITY,
            CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP());
  affected := SQLROWCOUNT;
  CALL AIRLINE_DWH.AUDIT.LOG_MERGE(:RUN_ID, 'CORE.LOAD_CORE', 'CORE.DIM_PASSENGER', :rows_before, :affected, :started_at);

  SELECT COUNT(*) INTO :rows_before FROM AIRLINE_DWH.CORE.DIM_AIRPORT;
  MERGE INTO AIRLINE_DWH.CORE.DIM_AIRPORT t
  USING (SELECT AIRPORT_NAME, COUNTRY_CODE, AIRPORT_CODE, CONTINENT_CODE
         FROM AIRLINE_DWH.CORE.V_BOOKINGS_CHANGES
         QUALIFY ROW_NUMBER() OVER (PARTITION BY AIRPORT_NAME, COUNTRY_CODE, AIRPORT_CODE
                   ORDER BY LOADED_AT DESC, SOURCE_FILE DESC, SOURCE_ROW DESC) = 1) s
  ON t.AIRPORT_NAME = s.AIRPORT_NAME
     AND t.COUNTRY_CODE = s.COUNTRY_CODE
     AND t.AIRPORT_CODE = s.AIRPORT_CODE
  WHEN MATCHED AND t.CONTINENT_CODE IS DISTINCT FROM s.CONTINENT_CODE THEN
    UPDATE SET CONTINENT_CODE = s.CONTINENT_CODE, UPDATED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN
    INSERT (AIRPORT_NAME, COUNTRY_CODE, AIRPORT_CODE, IATA_CODE, CONTINENT_CODE, UPDATED_AT)
    VALUES (s.AIRPORT_NAME, s.COUNTRY_CODE, s.AIRPORT_CODE,
            IFF(REGEXP_LIKE(s.AIRPORT_CODE, '[A-Z]{3}'), s.AIRPORT_CODE, NULL),
            s.CONTINENT_CODE, CURRENT_TIMESTAMP());
  affected := SQLROWCOUNT;
  CALL AIRLINE_DWH.AUDIT.LOG_MERGE(:RUN_ID, 'CORE.LOAD_CORE', 'CORE.DIM_AIRPORT', :rows_before, :affected, :started_at);

  -- The fact last: it needs the airport ids the MERGE above just created
  SELECT COUNT(*) INTO :rows_before FROM AIRLINE_DWH.CORE.FACT_FLIGHT;
  MERGE INTO AIRLINE_DWH.CORE.FACT_FLIGHT t
  USING (SELECT b.PASSENGER_ID,
                YEAR(b.DEPARTURE_DATE) * 10000 + MONTH(b.DEPARTURE_DATE) * 100
                  + DAY(b.DEPARTURE_DATE) AS DEPARTURE_DATE_KEY,
                a.AIRPORT_ID, b.PILOT_NAME, b.FLIGHT_STATUS, b.TICKET_TYPE,
                b.PASSENGER_STATUS, b.SOURCE_FILE, b.SOURCE_ROW
         FROM AIRLINE_DWH.CORE.V_BOOKINGS_CHANGES b
         LEFT JOIN AIRLINE_DWH.CORE.DIM_AIRPORT a
           ON a.AIRPORT_NAME = b.AIRPORT_NAME
          AND a.COUNTRY_CODE = b.COUNTRY_CODE
          AND a.AIRPORT_CODE = b.AIRPORT_CODE) s
  ON t.PASSENGER_ID = s.PASSENGER_ID
  WHEN MATCHED AND (t.DEPARTURE_DATE_KEY IS DISTINCT FROM s.DEPARTURE_DATE_KEY
                 OR t.AIRPORT_ID IS DISTINCT FROM s.AIRPORT_ID
                 OR t.PILOT_NAME IS DISTINCT FROM s.PILOT_NAME
                 OR t.FLIGHT_STATUS IS DISTINCT FROM s.FLIGHT_STATUS
                 OR t.TICKET_TYPE IS DISTINCT FROM s.TICKET_TYPE
                 OR t.PASSENGER_STATUS IS DISTINCT FROM s.PASSENGER_STATUS) THEN
    UPDATE SET DEPARTURE_DATE_KEY = s.DEPARTURE_DATE_KEY, AIRPORT_ID = s.AIRPORT_ID,
               PILOT_NAME = s.PILOT_NAME, FLIGHT_STATUS = s.FLIGHT_STATUS,
               TICKET_TYPE = s.TICKET_TYPE, PASSENGER_STATUS = s.PASSENGER_STATUS,
               SOURCE_FILE = s.SOURCE_FILE, SOURCE_ROW = s.SOURCE_ROW,
               UPDATED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN
    INSERT (PASSENGER_ID, DEPARTURE_DATE_KEY, AIRPORT_ID, PILOT_NAME, FLIGHT_STATUS,
            TICKET_TYPE, PASSENGER_STATUS, SOURCE_FILE, SOURCE_ROW, CREATED_AT, UPDATED_AT)
    VALUES (s.PASSENGER_ID, s.DEPARTURE_DATE_KEY, s.AIRPORT_ID, s.PILOT_NAME,
            s.FLIGHT_STATUS, s.TICKET_TYPE, s.PASSENGER_STATUS, s.SOURCE_FILE,
            s.SOURCE_ROW, CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP());
  affected := SQLROWCOUNT;
  CALL AIRLINE_DWH.AUDIT.LOG_MERGE(:RUN_ID, 'CORE.LOAD_CORE', 'CORE.FACT_FLIGHT', :rows_before, :affected, :started_at);

  COMMIT;

  SELECT LISTAGG(TARGET_TABLE || ' +' || ROWS_INSERTED || ' ~' || ROWS_UPDATED, ', ')
           WITHIN GROUP (ORDER BY LOG_ID)
    INTO :summary
  FROM AIRLINE_DWH.AUDIT.LOAD_LOG
  WHERE RUN_ID = :RUN_ID AND PROCEDURE_NAME = 'CORE.LOAD_CORE' AND STARTED_AT = :started_at;
  RETURN summary;
EXCEPTION
  WHEN OTHER THEN
    err := SQLERRM;
    ROLLBACK;
    INSERT INTO AIRLINE_DWH.AUDIT.LOAD_LOG
      (RUN_ID, PROCEDURE_NAME, TARGET_TABLE, STATUS, ERROR_MESSAGE, STARTED_AT, FINISHED_AT)
    VALUES (:RUN_ID, 'CORE.LOAD_CORE', 'CORE.*', 'FAILED', :err, :started_at, CURRENT_TIMESTAMP());
    RAISE;
END;
$$;
