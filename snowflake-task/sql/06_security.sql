-- A secure view on the fact table, filtered by a row access policy: each
-- analyst role sees only the flights of its continents. The policy sits on
-- the view, not on FACT_FLIGHT, so the pipeline itself is never filtered.
-- Row access policies need Enterprise edition or higher

-- 1. Two analyst roles (as ACCOUNTADMIN, like 01_setup.sql)
USE ROLE ACCOUNTADMIN;
CREATE ROLE IF NOT EXISTS AIRLINE_ANALYST_EU;
CREATE ROLE IF NOT EXISTS AIRLINE_ANALYST_AMERICAS;
GRANT ROLE AIRLINE_ANALYST_EU TO ROLE SYSADMIN;
GRANT ROLE AIRLINE_ANALYST_AMERICAS TO ROLE SYSADMIN;
GRANT USAGE ON WAREHOUSE AIRLINE_WH TO ROLE AIRLINE_ANALYST_EU;
GRANT USAGE ON WAREHOUSE AIRLINE_WH TO ROLE AIRLINE_ANALYST_AMERICAS;
SET my_user = '"' || CURRENT_USER() || '"';
GRANT ROLE AIRLINE_ANALYST_EU TO USER IDENTIFIER($my_user);
GRANT ROLE AIRLINE_ANALYST_AMERICAS TO USER IDENTIFIER($my_user);

-- 2. The policy and the secure view (as the owner of the DWH)
USE ROLE AIRLINE_ETL;
USE WAREHOUSE AIRLINE_WH;
USE DATABASE AIRLINE_DWH;
CREATE SCHEMA IF NOT EXISTS SECURITY;

-- Dropped first so that, on a re-run, the policy is free to be replaced
DROP VIEW IF EXISTS MART.V_FLIGHTS_SECURE;

-- Which role sees which continents; '*' means all of them
CREATE OR REPLACE TABLE SECURITY.CONTINENT_ACCESS (
  ROLE_NAME       VARCHAR NOT NULL,
  CONTINENT_CODE  VARCHAR(3) NOT NULL,
  CONSTRAINT PK_CONTINENT_ACCESS PRIMARY KEY (ROLE_NAME, CONTINENT_CODE)
);
INSERT INTO SECURITY.CONTINENT_ACCESS (ROLE_NAME, CONTINENT_CODE) VALUES
  ('AIRLINE_ETL', '*'),
  ('AIRLINE_ANALYST_EU', 'EU'),
  ('AIRLINE_ANALYST_AMERICAS', 'NAM'),
  ('AIRLINE_ANALYST_AMERICAS', 'SAM');

-- A row is visible when the current role is mapped to its continent or to '*'.
-- Roles missing from the table, ACCOUNTADMIN included, see nothing
CREATE OR REPLACE ROW ACCESS POLICY SECURITY.CONTINENT_POLICY
  AS (continent VARCHAR) RETURNS BOOLEAN ->
    EXISTS (SELECT 1
            FROM AIRLINE_DWH.SECURITY.CONTINENT_ACCESS m
            WHERE m.ROLE_NAME = CURRENT_ROLE()
              AND m.CONTINENT_CODE IN (continent, '*'));

-- The fact table for analysts. Secure: its definition and the tables behind it
-- stay hidden. Passenger and pilot names are left out
CREATE SECURE VIEW MART.V_FLIGHTS_SECURE AS
SELECT f.PASSENGER_ID,
       d.FULL_DATE AS DEPARTURE_DATE,
       a.AIRPORT_NAME,
       a.IATA_CODE,
       c.COUNTRY_NAME,
       a.CONTINENT_CODE,
       k.CONTINENT_NAME,
       f.FLIGHT_STATUS,
       f.TICKET_TYPE,
       p.NATIONALITY,
       p.GENDER,
       p.AGE
FROM AIRLINE_DWH.CORE.FACT_FLIGHT f
JOIN AIRLINE_DWH.CORE.DIM_DATE d      ON d.DATE_KEY = f.DEPARTURE_DATE_KEY
JOIN AIRLINE_DWH.CORE.DIM_AIRPORT a   ON a.AIRPORT_ID = f.AIRPORT_ID
JOIN AIRLINE_DWH.CORE.DIM_COUNTRY c   ON c.COUNTRY_CODE = a.COUNTRY_CODE
JOIN AIRLINE_DWH.CORE.DIM_CONTINENT k ON k.CONTINENT_CODE = a.CONTINENT_CODE
JOIN AIRLINE_DWH.CORE.DIM_PASSENGER p ON p.PASSENGER_ID = f.PASSENGER_ID;

ALTER VIEW MART.V_FLIGHTS_SECURE
  ADD ROW ACCESS POLICY SECURITY.CONTINENT_POLICY ON (CONTINENT_CODE);

-- Analysts can read the secure view, and no table
GRANT USAGE ON DATABASE AIRLINE_DWH TO ROLE AIRLINE_ANALYST_EU;
GRANT USAGE ON DATABASE AIRLINE_DWH TO ROLE AIRLINE_ANALYST_AMERICAS;
GRANT USAGE ON SCHEMA AIRLINE_DWH.MART TO ROLE AIRLINE_ANALYST_EU;
GRANT USAGE ON SCHEMA AIRLINE_DWH.MART TO ROLE AIRLINE_ANALYST_AMERICAS;
GRANT SELECT ON VIEW AIRLINE_DWH.MART.V_FLIGHTS_SECURE TO ROLE AIRLINE_ANALYST_EU;
GRANT SELECT ON VIEW AIRLINE_DWH.MART.V_FLIGHTS_SECURE TO ROLE AIRLINE_ANALYST_AMERICAS;

-- 3. Test it, one statement at a time. Secondary roles are switched off for
-- the session, so only the role in use counts
USE SECONDARY ROLES NONE;

USE ROLE AIRLINE_ANALYST_EU;
SELECT CONTINENT_CODE, COUNT(*) AS flights
FROM AIRLINE_DWH.MART.V_FLIGHTS_SECURE GROUP BY CONTINENT_CODE ORDER BY CONTINENT_CODE;

USE ROLE AIRLINE_ANALYST_AMERICAS;
SELECT CONTINENT_CODE, COUNT(*) AS flights
FROM AIRLINE_DWH.MART.V_FLIGHTS_SECURE GROUP BY CONTINENT_CODE ORDER BY CONTINENT_CODE;
-- The table behind the view is out of reach: "does not exist or not authorized"
SELECT COUNT(*) FROM AIRLINE_DWH.CORE.FACT_FLIGHT;
-- ...and so is the view's definition: is_secure is true, text is empty
SHOW VIEWS LIKE 'V_FLIGHTS_SECURE' IN SCHEMA AIRLINE_DWH.MART;

USE ROLE AIRLINE_ETL;
SELECT CONTINENT_CODE, COUNT(*) AS flights
FROM AIRLINE_DWH.MART.V_FLIGHTS_SECURE GROUP BY CONTINENT_CODE ORDER BY CONTINENT_CODE;
-- Where the policy is attached
SELECT POLICY_NAME, POLICY_KIND, REF_ENTITY_NAME, REF_ENTITY_DOMAIN, REF_ARG_COLUMN_NAMES, POLICY_STATUS
FROM TABLE(AIRLINE_DWH.INFORMATION_SCHEMA.POLICY_REFERENCES(
  REF_ENTITY_NAME => 'AIRLINE_DWH.MART.V_FLIGHTS_SECURE', REF_ENTITY_DOMAIN => 'VIEW'));

USE SECONDARY ROLES ALL;
